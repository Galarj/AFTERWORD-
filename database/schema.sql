-- 10. AUTOMATED INVENTORY & RETURN TRIGGERS
-- ----------------------------------------------------------------------------
-- Keeps books.available_copies in perfect sync whenever a loan is created or returned
CREATE OR REPLACE FUNCTION public.handle_book_loan_inventory()
RETURNS TRIGGER AS $$
BEGIN
    -- Case 1: When a loan is allowed & approved by admin (status becomes 'Borrowed')
    IF ((TG_OP = 'INSERT' AND NEW.status = 'Borrowed') OR (TG_OP = 'UPDATE' AND OLD.status = 'Requested' AND NEW.status = 'Borrowed')) THEN
        UPDATE public.books
        SET available_copies = GREATEST(available_copies - 1, 0)
        WHERE book_id = NEW.book_id;

    -- Case 2: When a borrowed book is returned
    ELSIF (TG_OP = 'UPDATE' AND OLD.status = 'Borrowed' AND NEW.status = 'Returned') THEN
        NEW.returned_at := NOW();
        UPDATE public.books
        SET available_copies = LEAST(available_copies + 1, total_copies)
        WHERE book_id = NEW.book_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE TRIGGER on_book_loan_inventory_change
    BEFORE INSERT OR UPDATE ON public.book_loans
    FOR EACH ROW EXECUTE FUNCTION public.handle_book_loan_inventory();

-- Keeps products.stock and products.is_available in perfect sync whenever an order is placed
CREATE OR REPLACE FUNCTION public.handle_product_order_stock()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE public.products
    SET 
        stock = GREATEST(stock - NEW.quantity, 0),
        is_available = CASE WHEN (stock - NEW.quantity) <= 0 THEN false ELSE is_available END
    WHERE product_id = NEW.product_id;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE TRIGGER on_product_order_stock_change
    AFTER INSERT ON public.order_items
    FOR EACH ROW EXECUTE FUNCTION public.handle_product_order_stock();



