-- 8. PHYSICAL CAFÉ SEATING TABLES & TABLE RESERVATIONS
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cafe_tables (
    table_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number VARCHAR(10) UNIQUE NOT NULL,      -- e.g. 'T01', 'T02', ... 'T16'
    capacity INT NOT NULL CHECK (capacity > 0),    -- e.g. 2, 4, 6, 8, 10
    location VARCHAR(100) NOT NULL,                -- 'Window Alcove', 'Main Hall', 'Communal Table', 'Reading Lounge'
    status VARCHAR(30) DEFAULT 'available' CHECK (status IN ('available', 'occupied', 'reserved', 'unavailable')),
    is_available BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.table_reservations (
    reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id BIGINT REFERENCES public.cafe_tables(table_id) ON DELETE CASCADE,
    table_number VARCHAR(10) NOT NULL,
    user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    patron_name VARCHAR(150) NOT NULL,
    patron_email VARCHAR(150) NOT NULL,
    patron_phone VARCHAR(50),
    reservation_date DATE NOT NULL,
    start_time VARCHAR(20) NOT NULL,              -- e.g. '17:00' or '5:00 PM'
    end_time VARCHAR(20),                        -- e.g. '18:30' or '6:30 PM'
    guest_count INT NOT NULL CHECK (guest_count > 0),
    status VARCHAR(30) DEFAULT 'Confirmed' CHECK (status IN ('Pending', 'Confirmed', 'Completed', 'Cancelled')),
    special_requests TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);


