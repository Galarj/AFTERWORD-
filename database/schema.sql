    borrowed_at TIMESTAMPTZ DEFAULT NOW(),
    due_date DATE NOT NULL,
    returned_at TIMESTAMPTZ
);

CREATE TABLE public.event_rsvps (
    rsvp_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES public.events(event_id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    guest_count INT NOT NULL DEFAULT 1 CHECK (guest_count > 0),
    status VARCHAR(30) DEFAULT 'Confirmed' CHECK (status IN ('Confirmed', 'Cancelled', 'Waitlist')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_user_event_rsvp UNIQUE (event_id, user_id)
);

CREATE TABLE public.wishlists (
